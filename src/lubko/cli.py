def launcher_source(entry: str) -> str:
    """Return stable launcher text resolving only through ``cli/current``.

    ``cli/current`` is the independently confirmed recovery anchor. No entry
    point, including ``lubko-supervisor``, has a second runtime-selection path.

    The shebang resolves the ``sh`` executable at generation time so generated
    launchers are directly executable on both GNU Linux (``/bin/sh``) and
    Termux (``/data/data/com.termux/files/usr/bin/sh``).

    Args:
        entry: Maintained entry point name.

    Returns:
        Executable shell script resolving the confirmed CLI commit.

    Raises:
        CliError: If ``sh`` is not found on PATH.
    """
    sh = shutil.which("sh")
    if sh is None:
        msg = "sh not found on PATH; a POSIX shell is required to generate launchers"
        raise CliError(msg)
    escaped_root = str(state_root()).replace("'", "'\\''")
    return _LAUNCHER_TEMPLATE.format(sh=sh, state_root=escaped_root, entry=entry)


def install_launchers(bin_dir: Path) -> None:
    """Write every stable launcher into a bin directory.

    Each launcher is written atomically and never changed by deployments. A
    launcher whose installed bytes and executable mode already match the
    generated source is left untouched, so reinstalling an already-valid
    deployment performs no persistent-filesystem writes at all.

    Args:
        bin_dir: Directory to install the launchers into.
    """
    bin_dir.mkdir(parents=True, exist_ok=True)
    for entry in ENTRY_POINTS:
        target = bin_dir / entry
        expected = launcher_source(entry)
        if _launcher_current(target, expected):
            continue
        temporary = bin_dir / f"{entry}.tmp"
        temporary.write_text(expected, encoding="utf-8")
        temporary.chmod(0o755)
        temporary.replace(target)


def _launcher_current(target: Path, expected: str) -> bool:
    """Return whether an installed launcher already matches the source.

    Args:
        target: Installed launcher path.
        expected: Generated launcher source.

    Returns:
        ``True`` only when the launcher exists as a regular file, is
        executable, and carries exactly the expected bytes. Reads only.
    """
    try:
        if target.is_symlink() or not target.is_file():
            return False
        if not os.access(target, os.X_OK):
            return False
        return target.read_text(encoding="utf-8") == expected
    except OSError:
        return False


def git_commit(repo: Path, timeout_seconds: float) -> str | None:
    """Return the full git commit of a checkout, read-only.

    Args:
        repo: Repository checkout to inspect.
        timeout_seconds: Bounded timeout.

    Returns:
        The full commit hash, or ``None`` when unavailable.
    """
    try:
        proc = subprocess.run(
            ["git", "-C", str(repo), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            timeout=timeout_seconds,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if proc.returncode != 0:
        return None
    commit = proc.stdout.strip()
    return commit or None
