SUPERVISOR_ENTRY: Final = "lubko-supervisor"
_SUPERVISOR_STATE_ROOT_PLACEHOLDER: Final = "@@LUBKO_STATE_ROOT@@"

_SUPERVISOR_LAUNCHER_TEMPLATE: Final = """#!/bin/sh
# Stable lubko-supervisor launcher (generated by lubko-install).
# Deployments never rewrite this file; they only switch the `current` symlink
# or publish a supervisor-runtime override that this script resolves.
#
# The override is a plain text file containing exactly one 40-hex commit plus
# newline.  When present and valid the supervisor daemon runs from that
# commit's sealed runtime instead of cli/current.  A corrupt or incomplete
# override fails closed: the launcher refuses to start rather than silently
# falling back to an unintended runtime.
set -u
ENTRY='lubko-supervisor'
STATE='@@LUBKO_STATE_ROOT@@'
OVERRIDE="$STATE/supervisor/supervisor-runtime"
LINK="$STATE/cli/current"

# --- resolve override or fall back to cli/current ---
if [ -f "$OVERRIDE" ]; then
  # Portable size gate: exactly 41 bytes (40 hex + newline).
  _OVERRIDE_SIZE="$(wc -c < "$OVERRIDE" 2>/dev/null)" || {
    printf '%s: could not read supervisor-runtime override size\\n' "$ENTRY" >&2
    exit 1
  }
  case "$_OVERRIDE_SIZE" in
    41) ;;
    *)
      printf '%s: supervisor-runtime override is not a valid 40-hex commit\\n' \\
        "$ENTRY" >&2
      exit 1
      ;;
  esac
  COMMIT="$(cat "$OVERRIDE")" || {
    printf '%s: could not read supervisor-runtime override\\n' "$ENTRY" >&2
    exit 1
  }
  # strict validation: exactly 40 lowercase hex chars, nothing else
  case "$COMMIT" in
    [0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f])
      ;;
    *)
      printf '%s: supervisor-runtime override is not a valid 40-hex commit\\n' \\
        "$ENTRY" >&2
      exit 1
      ;;
  esac
  ROOT="$STATE/cli/$COMMIT"
  if [ ! -d "$ROOT" ]; then
    printf '%s: supervisor-runtime override commit %s has no runtime dir\\n' \\
      "$ENTRY" "$COMMIT" >&2
    exit 1
  fi
  BIN="$ROOT/.venv/bin/$ENTRY"
  if [ ! -x "$BIN" ]; then
    printf '%s: supervisor-runtime override commit %s is incomplete\\n' \\
      "$ENTRY" "$COMMIT" >&2
    exit 1
  fi
  exec "$BIN" "$@"
fi

# --- no override: resolve through cli/current (normal path) ---
if [ ! -L "$LINK" ]; then
  printf '%s: no maintained Lubko CLI; run lubko-install\\n' "$ENTRY" >&2
  exit 1
fi
BASE="$(dirname "$LINK")"
TARGET="$(readlink "$LINK")" || exit 1
case "$TARGET" in
  /*) REL="$TARGET" ;;
  *) REL="$BASE/$TARGET" ;;
esac
ROOT="$(cd "$REL" 2>/dev/null && pwd -P)" || {
  printf '%s: maintained CLI root %s missing; reinstall\\n' "$ENTRY" "$REL" >&2
  exit 1
}
BIN="$ROOT/.venv/bin/$ENTRY"
if [ ! -x "$BIN" ]; then
  printf '%s: incomplete CLI root (%s); reinstall\\n' "$ENTRY" "$BIN" >&2
  exit 1
fi
exec "$BIN" "$@"
"""


def launcher_source(entry: str) -> str:
    """Return the stable shell launcher text for one maintained entry point.

    The ``lubko-supervisor`` entry uses a special launcher that checks for a
    temporary supervisor-runtime override before resolving through
    ``cli/current``.  All other entries resolve through ``cli/current`` only.

    The embedded state root is shell-quoted so a path containing a single
    quote cannot break the generated script.

    Args:
        entry: Maintained entry point name.

    Returns:
        Executable shell script resolving the active CLI commit.
    """
    escaped_root = str(state_root()).replace("'", "'\\''")
    if entry == SUPERVISOR_ENTRY:
        return _SUPERVISOR_LAUNCHER_TEMPLATE.replace(
            _SUPERVISOR_STATE_ROOT_PLACEHOLDER, escaped_root
        )
    return _LAUNCHER_TEMPLATE.format(state_root=escaped_root, entry=entry)


def install_launchers(bin_dir: Path) -> None:
    """Write every stable launcher into a bin directory.

    Each launcher is written atomically and never changed by deployments.

    Args:
        bin_dir: Directory to install the launchers into.
    """
    bin_dir.mkdir(parents=True, exist_ok=True)
    for entry in ENTRY_POINTS:
        target = bin_dir / entry
        temporary = bin_dir / f"{entry}.tmp"
        temporary.write_text(launcher_source(entry), encoding="utf-8")
        temporary.chmod(0o755)
        temporary.replace(target)


def git_commit(repo: Path, timeout_seconds: float) -> str | None:
    """Return the full git commit of a checkout, read-only.

    Args:
        repo: Repository checkout to inspect.
        timeout_seconds: Bounded timeout.

    Returns:
        The full commit hash, or ``None`` when unavailable.
    """
    try:
        proc = subprocess.run(
            ["git", "-C", str(repo), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            timeout=timeout_seconds,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if proc.returncode != 0:
        return None
    commit = proc.stdout.strip()
    return commit or None
