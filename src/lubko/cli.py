def _extract_archive(repo: Path, commit: str, destination: Path, timeout_seconds: float) -> None:
    """Extract the exact tree of a commit into a directory.

    Args:
        repo: Repository checkout that contains the commit.
        commit: Exact commit hash to extract.
        destination: Directory to receive the extracted tree.
        timeout_seconds: Bounded timeout for creating the Git archive.

    Raises:
        CliError: If the archive or extraction fails.
    """
    try:
        archived = subprocess.run(
            ["git", "-C", str(repo), "archive", commit],
            capture_output=True,
            timeout=timeout_seconds,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        msg = f"could not archive commit {commit}: {exc}"
        raise CliError(msg) from exc
    if archived.returncode != 0:
        detail = (
            archived.stderr or archived.stdout
        ).decode().strip() or f"exit code {archived.returncode}"
        msg = f"git archive of commit {commit} failed: {detail}"
        raise CliError(msg)
    try:
        with tarfile.open(fileobj=io.BytesIO(archived.stdout), mode="r:") as archive:
            archive.extractall(destination, filter="data")
    except (OSError, tarfile.TarError) as exc:
        msg = f"could not extract commit {commit}: {exc}"
        raise CliError(msg) from exc


def _sync_venv(uv_path: str, root: Path, timeout_seconds: float) -> None:
    """Synchronize the virtualenv of one extracted commit tree.

    Args:
        uv_path: Path to the ``uv`` executable.
        root: Extracted commit tree.
        timeout_seconds: Bounded timeout.

    Raises:
        CliError: If ``uv sync`` fails.
    """
    env = dict(os.environ)
    env.setdefault("UV_HTTP_TIMEOUT", UV_HTTP_TIMEOUT)
    try:
        proc = subprocess.run(
            [uv_path, "sync", "--frozen", "--project", str(root)],
            cwd=root,
            env=env,
            capture_output=True,
            text=True,
            timeout=timeout_seconds,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        msg = f"could not synchronize the CLI environment: {exc}"
        raise CliError(msg) from exc
    if proc.returncode != 0:
        lines = [line for line in (proc.stderr or proc.stdout).splitlines() if line]
        detail = "\n".join(lines[-10:]) or f"exit code {proc.returncode}"
        msg = f"uv sync for the CLI environment failed:\n{detail}"
        raise CliError(msg)


def install_entry_point_bridges(commit: str) -> None:
    """Bridge every retired entry point missing from one freshly built runtime.

    Retired names are normally installed by package metadata during ``uv sync``
    so even a predecessor builder sees them before its own completeness check.
    This post-sync materialization is defense in depth for fresh builders and
    runs before the binding manifest is written, so any fallback bridge is part
    of the manifest-bound content identity.

    A name that already exists is left untouched: package-installed
    compatibility scripts and any real entry point always win.

    Args:
        commit: Exact commit hash of the runtime being built.

    Raises:
        CliError: If a bridge script cannot be materialized.
    """
    bin_dir = cli_commit_dir(commit) / ".venv" / "bin"
    for entry in RETIRED_ENTRY_POINTS:
        script = bin_dir / entry
        if script.exists():
            continue
        try:
            script.write_text(_BRIDGE_TEMPLATE.format(entry=entry), encoding="utf-8")
            script.chmod(0o755)
        except OSError as exc:
            msg = f"could not bridge the retired entry point {entry} for commit {commit}: {exc}"
            raise CliError(msg) from exc


def build_cli_root(repo: Path, commit: str, uv_path: str, timeout_seconds: float) -> Path:
    """Build or reuse the immutable CLI environment for one exact commit.

    The environment is extracted with ``git archive`` and synchronized with
    ``uv sync`` directly at its final location, so entry-point shebangs stay
    valid, and the retired entry points are bridged in before the tree is
    manifest-bound and sealed. Building the same commit twice is idempotent and
    never rewrites an already-sealed usable environment. Once materialized and
    verified it is sealed read-only; an unsealed/corrupt/wrong-commit tree is
    unsealed, removed, and rebuilt rather than trusted.

    Args:
        repo: Repository checkout that contains the commit.
        commit: Exact commit hash.
        uv_path: Path to the ``uv`` executable.
        timeout_seconds: Bounded timeout per step.

    Returns:
        The commit's sealed CLI environment directory.

    Raises:
        CliError: If the environment cannot be built or sealed.
    """
    validate_commit_name(commit)
    destination = cli_commit_dir(commit)
    if runtime_is_usable(commit):
        return destination
    if current_commit() == commit:
        msg = (
            f"refusing to rebuild confirmed CLI environment for commit {commit}; "
            "its manifest-bound content identity could not be restored"
        )
        raise CliError(msg)
    unseal_runtime(commit)
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True, exist_ok=True)
    try:
        _extract_archive(repo, commit, destination, timeout_seconds)
        _sync_venv(uv_path, destination, timeout_seconds)
    except CliError:
        shutil.rmtree(destination, ignore_errors=True)
        raise
    if not _root_is_usable(commit):
        shutil.rmtree(destination, ignore_errors=True)
        msg = f"CLI environment for commit {commit} is incomplete after build"
        raise CliError(msg)
    install_entry_point_bridges(commit)
    _write_runtime_manifest(commit)
    seal_runtime(commit)
    if not runtime_is_usable(commit):
        unseal_runtime(commit)
        shutil.rmtree(destination, ignore_errors=True)
        msg = f"CLI environment for commit {commit} could not be sealed"
        raise CliError(msg)
    return destination


def set_current(commit: str) -> None:
    """Crash-durably select the commit the maintained CLIs resolve to.

    ``cli/current`` is recovery authority for the maintained CLI environment:
    every maintained command resolves through it, so the symlink switch must be
    confirmed durable before the activation is reported as successful.

    Args:
        commit: Exact commit hash to activate.

    Raises:
        CliError: If the pointer cannot be switched or ``commit`` is invalid.
    """
    validate_commit_name(commit)
    try:
        write_symlink_durable(current_link_path(), commit)
    except DurabilityError as exc:
        msg = f"could not activate CLI commit {commit}: {exc}"
        raise CliError(msg) from exc


def reconcile_pointer(commit: str) -> bool:
    """Idempotently repair the active pointer so it selects one commit.

    The switch happens only when the commit's environment is already sealed and
    usable, so a repair never activates an incomplete, unsealed, corrupt, or
    wrong-commit root and never touches a provisional candidate that is not
    yet the confirmed commit. An already-current pointer is only blessed when
    the runtime it points to is itself usable.

    Args:
        commit: Exact commit hash the pointer should select.

    Returns:
        ``True`` when the pointer now selects a usable runtime (there was
        nothing to repair, or the repair succeeded), ``False`` when the
        runtime is missing, unusable, invalid, or the pointer could not be
        switched.
    """
    if not runtime_is_usable(commit):
        return False
    if current_commit() == commit:
        return True
    try:
        set_current(commit)
    except CliError:
        return False
    return True


def supervisor_authoritative_commits() -> set[str]:
    """Return every runtime commit the supervisor may still rely on.

    The union covers:
    - the durable desired intent (worker target commit);
    - the daemon's applied state commit;
    - the supervisor's own runtime commit (the code the supervisor is
      executing from, which may differ from the worker commit after a
      deployment).

    All three can name a runtime the supervisor daemon or its maintained
    worker must still be able to start (including on restart and during
    spawned two-phase handoff), so garbage collection must never delete them —
    even when they are absent from an explicit keep list.

    Returns:
        The set of valid 40-hex commits that must be preserved.
    """
    preserved: set[str] = set()
    try:
        desired = read_desired_client()
    except (DesiredIntentError, ConnectionError, OSError):
        desired = None
    if desired is not None and is_valid_commit_name(desired.commit):
        preserved.add(desired.commit)
    try:
        state = read_state_client()
    except (ConnectionError, OSError):
        return preserved
    state_commit = state.commit
    if state_commit is not None and is_valid_commit_name(state_commit):
        preserved.add(state_commit)
    # The supervisor's own runtime must never be garbage-collected while
    # the supervisor is still executing from it (before a successful
    # spawned two-phase handoff).
    sr_commit = state.supervisor_runtime_commit
    if sr_commit is not None and is_valid_commit_name(sr_commit):
        preserved.add(sr_commit)
    return preserved


def remove_cli_root(commit: str) -> None:
    """Remove one commit's CLI environment if it is not authoritative.

    A sealed runtime is unsealed first so the explicit removal actually works.
    An invalid commit name is never removed, and neither is any
    supervisor-authoritative commit (desired intent or applied state): deleting a
    runtime the supervisor may still start would create
    worker/CLI divergence and a later outage (fail closed).

    Args:
        commit: Exact commit hash to remove.
    """
    if not is_valid_commit_name(commit) or commit == current_commit():
        return
    if commit in supervisor_authoritative_commits():
        return
    root = cli_commit_dir(commit)
    if not root.exists():
        return
    unseal_runtime(commit)
    shutil.rmtree(root, ignore_errors=True)


def gc_cli_roots(keep: Sequence[str]) -> None:
    """Remove every CLI environment except the commits listed.

    The environment selected by the ``current`` symlink is always preserved,
    even when it is absent from ``keep``. Activation may have failed after
    durable state was written, so a cleanup must never delete the root that the
    global CLIs currently resolve to. Every supervisor-authoritative runtime
    (desired intent or applied state) is also
    preserved: deleting a runtime the supervisor or its maintained worker may
    still start would create worker/CLI divergence and a later outage.
    Sealed environments are unsealed first so the explicit GC actually removes
    them; commit-addressed paths are validated before any unseal.

    Args:
        keep: Commits whose environments must be retained.
    """
    keep_set = set(keep)
    current = current_commit()
    if current is not None:
        keep_set.add(current)
    keep_set.update(supervisor_authoritative_commits())
    for path in cli_root_dir().iterdir() if cli_root_dir().is_dir() else ():
        if path.name in {CURRENT_LINK_NAME, CURRENT_TMP_NAME}:
            continue
        if path.name not in keep_set:
            if is_valid_commit_name(path.name):
                unseal_runtime(path.name)
            shutil.rmtree(path, ignore_errors=True)


