"""Coherent resolution of the maintained Lubko command line tools.

The global entry points (``lubko-worker``, ``lubko-supervisor``, ``lubko-deploy``,
``lubko-deploy-ctl``, and ``lubko-install``) must always
resolve to code from the *confirmed* maintained commit. A supervised
deployment checks out a provisional candidate and may roll back to the
previous commit at any time before confirmation, so the global CLIs must never
be stranded on candidate code.

This module keeps the CLIs coherent with a stable indirection instead of
rewriting an installed ``uv`` tool in place:

- every global entry point is a small stable launcher script, written once by
  ``lubko-install`` and never rewritten by a deployment;
- each commit owns an immutable per-commit CLI environment under
  ``$XDG_STATE_HOME/lubko/cli/<commit>/``: a plain ``git archive`` extraction
  of the exact commit tree plus the virtualenv ``uv sync`` creates there; at
  materialization it is bound to the exact full commit by a manifest carrying
  a deterministic content digest, then ``sealed`` read-only — sealing never
  rewrites that identity, so normal operation never writes to it and a
  modified/re-sealed tree is never trusted;
- ``$XDG_STATE_HOME/lubko/cli/current`` is a symlink selecting the active
  commit and is switched with a single atomic ``os.replace``.

Deployments build the candidate environment during the provisional phase and
only move ``current`` after durable ``confirmed`` state exists. A rollback
therefore never needs to restore the CLIs: the pointer was never moved, so the
prior confirmed CLI version is preserved by construction.

A sealed runtime is only ever made writable again (``unseal_runtime``) for an
explicit rebuild/removal/GC operation; it is never unsealed during ordinary
start, restart, probe, or crash recovery.
"""

