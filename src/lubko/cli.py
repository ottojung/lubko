def is_valid_commit_name(name: str) -> bool:
    """Return whether ``name`` is exactly 40 hexadecimal characters.

    Runtime directories are addressed by the full commit SHA alone; a short
    ref, a relative path, or any non-hex value must never resolve to a runtime
    path.

    Args:
        name: Candidate commit name.

    Returns:
        ``True`` when the name is exactly 40 hex characters.
    """
    return COMMIT_PATH_RE.fullmatch(name) is not None


def validate_commit_name(commit: str) -> None:
    """Require ``commit`` to be exactly 40 hexadecimal characters.

    Args:
        commit: Exact commit hash.

    Raises:
        CliError: If the value is not a full 40-hex-character commit.
    """
    if not is_valid_commit_name(commit):
        msg = "runtime commits must be exactly 40 hexadecimal characters"
        raise CliError(msg)


def cli_commit_dir(commit: str) -> Path:
    """Return the immutable CLI environment directory of one commit.

    Args:
        commit: Exact 40-character commit hash.

    Returns:
        The per-commit CLI root.
    """
    validate_commit_name(commit)
    return cli_root_dir() / commit


def current_link_path() -> Path:
    """Return the symlink selecting the active maintained CLI commit.

    Returns:
        The ``current`` symlink path.
    """
    return cli_root_dir() / CURRENT_LINK_NAME


def current_commit() -> str | None:
    """Return the commit the maintained CLIs currently resolve to.

    Returns:
        The active commit, or ``None`` when no maintained CLI is active.
    """
    try:
        target = current_link_path().readlink()
    except OSError:
        return None
    return Path(target).name


def cli_entry_executable(commit: str, entry: str) -> Path | None:
    """Return the executable for an entry point within one commit root.

    Args:
        commit: Exact commit hash.
        entry: Maintained entry point name.

    Returns:
        The virtualenv entry-point script, or ``None`` when it is absent.
    """
    executable = cli_commit_dir(commit) / ".venv" / "bin" / entry
    if executable.is_file():
        return executable
    return None


def _root_is_usable(commit: str) -> bool:
    """Return whether a commit's CLI environment looks fully built.

    Every maintained entry point must exist: older commits may predate one of
    the seven entry points, and activating such a root would leave that global
    command broken.

    Args:
        commit: Exact commit hash.

    Returns:
        ``True`` when the per-commit environment has every entry point.
    """
    return all(cli_entry_executable(commit, entry) is not None for entry in ENTRY_POINTS)


def manifest_path(commit: str) -> Path:
    """Return the binding-manifest path of one commit runtime.

    The manifest binds the materialized tree to the exact full commit, the
    runtime schema, and a deterministic content digest of the sealed tree so a
    stale, wrong-commit, partially built, or tampered tree can never be
    mistaken for the exact deployed runtime.

    Args:
        commit: Exact 40-character commit hash.

    Returns:
        The ``lubko-runtime.json`` path inside the commit runtime.
    """
    return cli_commit_dir(commit) / RUNTIME_MANIFEST_NAME


def _lstat_mode(path: Path) -> int | None:
    """Return the mode of a path without following a trailing symlink.

    Args:
        path: Path to inspect.

    Returns:
        The link-safe mode bits, or ``None`` when the entry is gone/unreadable.
    """
    try:
        return path.lstat().st_mode
    except OSError:
        return None


def _seal_tree(root: Path) -> None:
    """Remove every write bit below ``root`` so normal operation cannot modify it.

    Symlinks are never chmodded: mutating a symlink's mode bits would follow
    the link and alter an external target. Only regular files and directories
    are sealed.

    Args:
        root: Runtime tree to make read-only.
    """
    for dirpath, dirnames, filenames in os.walk(root):
        for name in (*dirnames, *filenames):
            with suppress(OSError):
                path = Path(dirpath) / name
                mode = path.lstat().st_mode
                if not stat.S_ISLNK(mode):
                    path.chmod(mode & ~_WRITE_BITS)
        with suppress(OSError):
            directory = Path(dirpath)
            mode = directory.lstat().st_mode
            if not stat.S_ISLNK(mode):
                directory.chmod(mode & ~_WRITE_BITS)


def _unseal_tree(root: Path) -> None:
    """Restore owner-write permission below ``root`` for a rebuild/removal/GC.

    Symlinks are deliberately skipped: only regular files and directories are
    made writable, so an external symlink target retains its own mode.

    Args:
        root: Runtime tree to make writable again.
    """
    for dirpath, dirnames, filenames in os.walk(root):
        for name in (*dirnames, *filenames):
            with suppress(OSError):
                path = Path(dirpath) / name
                mode = path.lstat().st_mode
                if not stat.S_ISLNK(mode):
                    path.chmod(mode | stat.S_IWUSR)
        with suppress(OSError):
            directory = Path(dirpath)
            mode = directory.lstat().st_mode
            if not stat.S_ISLNK(mode):
                directory.chmod(mode | stat.S_IWUSR)


def _tree_is_read_only(root: Path) -> bool:
    """Return whether every entry below ``root`` is free of write bits.

    Symlinks are inspected with ``lstat`` and excluded from the write-bit
    rule: their mode bits cannot escape the sealed runtime because sealing
    never follows a symlink, and ``os.walk`` does not descend into symlinked
    directories.

    Args:
        root: Runtime tree to verify.

    Returns:
        ``True`` when no regular file or directory under ``root`` is writable.
    """
    if not root.is_dir():
        return False
    for dirpath, dirnames, filenames in os.walk(root):
        for name in (*dirnames, *filenames):
            mode = _lstat_mode(Path(dirpath) / name)
            if mode is None:
                return False
            if stat.S_ISLNK(mode):
                continue
            if mode & _WRITE_BITS:
                return False
        mode = _lstat_mode(Path(dirpath))
        if mode is None or mode & _WRITE_BITS:
            return False
    return True


def _file_content_digest(path: Path) -> bytes:
    """Return the raw SHA-256 of one regular file's contents.

    Args:
        path: Regular file to digest.

    Returns:
        The 32 raw digest bytes.
    """
    hasher = hashlib.sha256()
    with path.open("rb") as handle:
        while True:
            chunk = handle.read(1024 * 1024)
            if not chunk:
                return hasher.digest()
            hasher.update(chunk)


def _runtime_content_digest(root: Path) -> bytes:
    """Return the deterministic content digest of one runtime tree.

    The digest binds every entry below ``root`` except the binding manifest
    itself: regular files contribute their relative path, permission mode
    (write bits masked so sealing order never matters), and a content digest;
    symlinks contribute their relative path and exact link target without ever
    following the link; directories and any other entry type contribute their
    relative path (and mode where meaningful). Each contribution is
    length-prefixed, so added, removed, renamed, or tampered entries always
    change the digest.

    Args:
        root: Runtime tree to digest.

    Returns:
        The raw SHA-256 digest bytes over the canonical tree encoding.
    """
    entries: list[tuple[str, Path, os.stat_result]] = []

    def collect(directory: Path) -> None:
        with os.scandir(directory) as iterator:
            for entry in iterator:
                path = Path(entry.path)
                rel = path.relative_to(root).as_posix()
                if rel == RUNTIME_MANIFEST_NAME:
                    continue
                info = path.lstat()
                entries.append((rel, path, info))
                if stat.S_ISDIR(info.st_mode):
                    collect(path)

    collect(root)
    hasher = hashlib.sha256()

    def update(data: bytes) -> None:
        hasher.update(len(data).to_bytes(8, "big"))
        hasher.update(data)

    for rel, path, info in sorted(entries, key=itemgetter(0)):
        update(rel.encode("utf-8"))
        if stat.S_ISREG(info.st_mode):
            update(b"f")
            update((info.st_mode & ~_WRITE_BITS & 0o777).to_bytes(2, "big"))
            update(_file_content_digest(path))
        elif stat.S_ISLNK(info.st_mode):
            update(b"l")
            update(os.fspath(path.readlink()).encode("utf-8"))
        elif stat.S_ISDIR(info.st_mode):
            update(b"d")
        else:
            update(b"o")
            update((info.st_mode & ~_WRITE_BITS & 0o777).to_bytes(2, "big"))
    return hasher.digest()


def _write_runtime_manifest(commit: str) -> None:
    """Bind one materialized runtime to its exact commit with a content digest.

    The expected identity of a commit runtime is established exactly once, at
    materialization time, from the tree just extracted from the exact commit
    (``git archive`` plus ``uv sync``). Sealing later only changes permissions
    and never rewrites this manifest, so a tree modified after materialization
    can never be re-blessed while still claiming ``commit``.

    Args:
        commit: Exact 40-character commit hash.

    Raises:
        CliError: If the runtime tree cannot be digested.
    """
    root = cli_commit_dir(commit)
    try:
        content_digest = _runtime_content_digest(root).hex()
    except OSError as exc:
        msg = f"could not digest the runtime tree for commit {commit}: {exc}"
        raise CliError(msg) from exc
    manifest = {
        "schema_version": RUNTIME_MANIFEST_SCHEMA,
        "commit": commit,
        "content_digest": content_digest,
    }
    manifest_path(commit).write_text(json.dumps(manifest, sort_keys=True) + "\n", encoding="utf-8")


def seal_runtime(commit: str) -> None:
    """Seal one materialized commit runtime read-only.

    Only permission bits below the runtime tree are removed: the integrity
    manifest is written at materialization time and is never rewritten here, so
    a later unseal/reseal cannot redefine the commit-bound expected identity.
    Normal operation (start, restart, probe, crash recovery) must only ever use
    a sealed runtime whose manifest is verified. Symlinks in the tree are never
    followed or chmodded.

    Args:
        commit: Exact 40-character commit hash to seal.
    """
    validate_commit_name(commit)
    root = cli_commit_dir(commit)
    if not root.is_dir():
        return
    _seal_tree(root)


def unseal_runtime(commit: str) -> None:
    """Make a sealed commit runtime writable for an explicit rebuild/removal/GC.

    This is the deliberate, supported exception to read-only operation. It is
    only invoked by operations that repair or remove the tree; ordinary
    supervised start/restart never unseals. Symlinks in the tree are never
    followed or chmodded.

    Args:
        commit: Exact 40-character commit hash to unseal.
    """
    validate_commit_name(commit)
    root = cli_commit_dir(commit)
    if root.is_dir():
        _unseal_tree(root)


def _manifest_digest(data: object, commit: str) -> bytes | None:
    """Return the tree digest recorded by a manifest when it binds ``commit``.

    Args:
        data: Parsed manifest document.
        commit: Exact commit the manifest must bind.

    Returns:
        The recorded content-digest bytes, or ``None`` when the manifest does
        not bind ``commit`` under the current schema or carries no valid digest.
    """
    if not (
        isinstance(data, dict)
        and data.get("schema_version") == RUNTIME_MANIFEST_SCHEMA
        and data.get("commit") == commit
    ):
        return None
    expected = data.get("content_digest")
    if not isinstance(expected, str):
        return None
    try:
        return bytes.fromhex(expected)
    except ValueError:
        return None


def runtime_is_usable(commit: str) -> bool:
    """Return whether a commit runtime is complete, exactly bound, and sealed.

    An unsealed, incomplete, wrong-commit, corrupt, or content-tampered tree is
    deliberately reported unusable so callers fail closed instead of launching
    arbitrary mutable code. The manifest's ``content_digest`` is recomputed over
    the current tree on every call, so a runtime that was unsealed, modified,
    and re-sealed without regenerating the manifest is rejected. An invalid
    commit name is never usable.

    Args:
        commit: Exact 40-character commit hash.

    Returns:
        ``True`` only when every entry point exists, the manifest binds the
        tree to ``commit`` under the current schema, the tree is read-only, and
        the recomputed tree digest matches the manifest.
    """
    if not is_valid_commit_name(commit) or not _root_is_usable(commit):
        return False
    try:
        data = json.loads(manifest_path(commit).read_text())
    except (OSError, ValueError):
        return False
    expected = _manifest_digest(data, commit)
    if expected is None:
        return False
    root = cli_commit_dir(commit)
    if not _tree_is_read_only(root):
        return False
    try:
        return _runtime_content_digest(root) == expected
    except OSError:
        return False


