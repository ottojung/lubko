"""Coherent resolution of the maintained Lubko command line tools.

The global entry points (``lubko-agent``, ``lubko-worker``, ``lubko-deploy``,
``lubko-deploy-ctl``, ``lubko-install``, and ``my-lubko-agent``) must always
resolve to code from the *confirmed* maintained commit. A supervised
deployment checks out a provisional candidate and may roll back to the
previous commit at any time before confirmation, so the global CLIs must never
be stranded on candidate code.

This module keeps the CLIs coherent with a stable indirection instead of
rewriting an installed ``uv`` tool in place:

- every global entry point is a small stable launcher script, written once by
  ``lubko-install`` and never rewritten by a deployment;
- each commit owns an immutable per-commit CLI environment under
  ``$XDG_STATE_HOME/lubko/cli/<commit>/``: a plain ``git archive`` extraction
  of the exact commit tree plus the virtualenv ``uv sync`` creates there; at
  materialization it is bound to the exact full commit by a manifest carrying
  a deterministic content digest, then ``sealed`` read-only — sealing never
  rewrites that identity, so normal operation never writes to it and a
  modified/re-sealed tree is never trusted;
- ``$XDG_STATE_HOME/lubko/cli/current`` is a symlink selecting the active
  commit and is switched with a single atomic ``os.replace``.

Deployments build the candidate environment during the provisional phase and
only move ``current`` after durable ``confirmed`` state exists. A rollback
therefore never needs to restore the CLIs: the pointer was never moved, so the
prior confirmed CLI version is preserved by construction.

A sealed runtime is only ever made writable again (``unseal_runtime``) for an
explicit rebuild/removal/GC operation; it is never unsealed during ordinary
start, restart, probe, or crash recovery.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import stat
import subprocess
from contextlib import suppress
from operator import itemgetter
from pathlib import Path
from typing import TYPE_CHECKING, Final

from lubko.state import cli_root_dir, state_root
from lubko.supervise import read_supervisor_runtime_override

if TYPE_CHECKING:
    from collections.abc import Sequence

ENTRY_POINTS: Final = (
    "lubko-agent",
    "lubko-worker",
    "lubko-supervisor",
    "lubko-deploy",
    "lubko-deploy-ctl",
    "lubko-install",
    "my-lubko-agent",
)
CURRENT_LINK_NAME: Final = "current"
CURRENT_TMP_NAME: Final = "current.tmp"
DEFAULT_BUILD_TIMEOUT_SECONDS: Final = 600.0
UV_HTTP_TIMEOUT: Final = "30"

RUNTIME_MANIFEST_NAME: Final = "lubko-runtime.json"
RUNTIME_MANIFEST_SCHEMA: Final = 2
COMMIT_PATH_RE: Final = re.compile(r"[0-9a-fA-F]{40}")

_WRITE_BITS: Final = stat.S_IWUSR | stat.S_IWGRP | stat.S_IWOTH

_LAUNCHER_TEMPLATE: Final = """#!/bin/sh
# Stable Lubko launcher (generated by lubko-install). Deployments never rewrite
# this file; they only switch the `current` symlink that this script resolves.
set -u
LINK='{state_root}/cli/current'
ENTRY='{entry}'
if [ ! -L "$LINK" ]; then
  printf '%s: no maintained Lubko CLI; run lubko-install\\n' "$ENTRY" >&2
  exit 1
fi
BASE="$(dirname "$LINK")"
TARGET="$(readlink "$LINK")" || exit 1
case "$TARGET" in
  /*) REL="$TARGET" ;;
  *) REL="$BASE/$TARGET" ;;
esac
ROOT="$(cd "$REL" 2>/dev/null && pwd -P)" || {{
  printf '%s: maintained CLI root %s missing; reinstall\\n' "$ENTRY" "$REL" >&2
  exit 1
}}
BIN="$ROOT/.venv/bin/$ENTRY"
if [ ! -x "$BIN" ]; then
  printf '%s: incomplete CLI root (%s); reinstall\\n' "$ENTRY" "$BIN" >&2
  exit 1
fi
exec "$BIN" "$@"
"""


class CliError(RuntimeError):
    """Raised when a maintained CLI environment cannot be built or switched."""


